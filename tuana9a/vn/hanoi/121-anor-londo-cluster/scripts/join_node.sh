#!/usr/bin/env bash
set -euo pipefail

is_control_plane=$1

kube_join_command_txt="./tmp/kube_join_command.txt" # NOTE: should be generated by ./get_join_command.sh at this point

SSH_OPTS=(-o StrictHostKeyChecking=no -i "${key_file}")

JOIN_OPTS=""
if [[ "$is_control_plane" == "1" ]]; then
  JOIN_OPTS+="--control-plane"
fi

SSH_OPTS=(-o StrictHostKeyChecking=no -i "$key_file")

ssh ${SSH_OPTS[@]} "$ssh_user@$node_ip" \
  "set -euo pipefail; \
  sudo $(cat $kube_join_command_txt) $JOIN_OPTS"